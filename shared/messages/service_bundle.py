"""Message bundles for services that ship on their own.

Some services (the signature detector) are built and deployed without the repo's `shared` package, so they cannot
import shared.messages. Each carries instead:

  messages.json         only the messages that service asks for, in every language that has them
  service_messages.py   a tiny loader (standard library only) with the same get_message(key, locale, **variables) call

Both are generated from the main taxonomy by `python -m shared.messages.build`, so there is still one source of truth. Never edit them by hand.
"""
import json
import re
from pathlib import Path

# service directory (relative to the repo root) -> how its code imports the loader
SERVICES = {
    "apps/sig_detector": "service_messages",     # its image holds only main.py (and now these two files); `shared` is optional there
}

_KEY_CALL = re.compile(r"get_message\(\s*[\"']([A-Z][A-Z0-9_]+)[\"']")

LOADER_SOURCE = '''"""Generated by `python -m shared.messages.build` from shared/messages/locales/messages.yaml. Do not edit.

Wording for this service. It carries its own copy because the service is deployed without the repo's `shared` package.
get_message(key, locale="en", **variables): the message in that language, or English when the language has none, or the key itself
when nothing has it (a service never fails because of a message)."""
import json
import os

_BUNDLE = None


def _bundle():
    global _BUNDLE
    if _BUNDLE is None:
        try:
            with open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "messages.json"), encoding="utf-8") as fh:
                _BUNDLE = json.load(fh)
        except (OSError, ValueError):
            _BUNDLE = {}
    return _BUNDLE


def get_message(key, locale="en", **variables):
    bundle = _bundle()
    text = (bundle.get(locale) or {}).get(key) or (bundle.get("en") or {}).get(key)
    if text is None:
        return key
    try:
        return text.format(**variables)
    except (KeyError, IndexError, ValueError):
        return text
'''


def service_keys(directory) -> set:
    """The message keys a service's code asks for."""
    keys = set()
    for path in Path(directory).rglob("*.py"):
        if path.name == "service_messages.py" or "__pycache__" in path.parts:
            continue
        keys.update(_KEY_CALL.findall(path.read_text(encoding="utf-8", errors="ignore")))
    return keys


def write_service_bundles(root, registry, services=None) -> dict:
    """Write messages.json and service_messages.py into every service directory. Returns {service: number of messages}."""
    root = Path(root)
    written = {}
    en = registry._cache.get("en", {})
    for service in (services or SERVICES):
        directory = root / service
        if not directory.is_dir():
            continue
        keys = service_keys(directory)
        bundle = {"en": {}, "hi": {}}
        for locale in ("en", "hi"):
            entries = registry._cache.get(locale, {})
            for key in sorted(keys):
                text = entries.get(key).text if entries.get(key) else ""
                if text:
                    bundle[locale][key] = text
        missing = sorted(k for k in keys if k not in en)
        if missing:
            raise ValueError(f"{service} asks for messages that do not exist: {missing}")
        (directory / "messages.json").write_text(json.dumps(bundle, ensure_ascii=False, indent=1, sort_keys=True), encoding="utf-8")
        (directory / "service_messages.py").write_text(LOADER_SOURCE, encoding="utf-8")
        written[service] = len(keys)
    return written
