# ─────────────────────────────────────────────────────────────────────────────
# Lookups — O(1) access by step_id + pipeline
# ─────────────────────────────────────────────────────────────────────────────

_INWARD_INDEX:  dict[str, PipelineStep] = {s.step_id: s for s in INWARD_STEPS}
_OUTWARD_INDEX: dict[str, PipelineStep] = {s.step_id: s for s in OUTWARD_STEPS}


def get_step(step_id: str, pipeline: str) -> PipelineStep | None:
    """Return step definition or None if not found."""
    idx = _INWARD_INDEX if pipeline == "INWARD" else _OUTWARD_INDEX
    return idx.get(step_id)


def steps_for(pipeline: str) -> list[PipelineStep]:
    """Return ordered step list for the given pipeline."""
    return INWARD_STEPS if pipeline == "INWARD" else OUTWARD_STEPS
