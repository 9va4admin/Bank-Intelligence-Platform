"""Generate apps/web/src/shared/config/centralBankOfIndiaBranches.js from data/cboi_branches.csv (DEMO ONLY)."""
import csv, json, re, sys

src = sys.argv[1] if len(sys.argv) > 1 else "data/cboi_branches.csv"
dst = "apps/web/src/shared/config/centralBankOfIndiaBranches.js"


def title(s: str) -> str:
    return re.sub(r"[A-Za-z]+", lambda m: m.group().capitalize(), s.strip())


rows = []
for r in csv.DictReader(open(src, encoding="utf-8")):
    rows.append({
        "ifsc": r["IFSC_CODE"], "micr": r["MICR_CODE"].strip(), "name": title(r["BRANCH_NAME"]), "city": title(r["DIST_NAME"]),
        "district": title(r["DIST_NAME"]), "state": title(r["STATE_UNION_TERRITORY"]), "pin": r["PIN_CODE"].strip(),
        "phone": (r["MOBILE_NO"] or r["LAND_LINE_NO"]).strip(), "address": r["ADDRESS"].strip(), "region": r["REGION"].strip(),
    })
body = ",\n".join("  " + json.dumps(x, ensure_ascii=False) for x in rows)
open(dst, "w", encoding="utf-8").write(
    "/**\n * Central Bank of India branch directory - generated by scripts/gen_cboi_branches_js.py from the bank's public\n"
    f" * branch locator (centralbank.bank.in), {len(rows)} branches.\n * DEMO ONLY - not imported in production.\n */\n\n"
    f"export const CENTRAL_BANK_BRANCHES = [\n{body}\n]\n")
print(len(rows), "branches ->", dst)
